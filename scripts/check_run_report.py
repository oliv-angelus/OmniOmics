#!/usr/bin/env python3
"""Checks that run_report.generate_report() actually produces a report.

Run it before a release, or after touching run_report.py, tool_versions.py or
any pipeline's `workflow/rules/*.smk`:

    .venv/bin/python3 scripts/check_run_report.py

Exits non-zero if anything is wrong, so it can gate a build.

It exists because this failed silently for the entire life of the project. A
one-character bug in tool_versions.py (`m.start` instead of `m.start()`, so a
bound method reached a slice index) made generate_report raise TypeError on the
first active tool of any pipeline. The only call site, in main.py, wraps
write_report in `try/except` and emits `[could not write run report: ...]` into
the run log -- so runs finished normally, nothing looked broken, and
run_report.txt simply never appeared in any output folder. Nobody noticed until
a report was generated by hand for something else.

That shape of bug -- a broken feature behind a swallowed exception -- does not
announce itself, so it gets a mechanical check.

For each of the five pipelines, with a handful of its own tools marked active:

1. **The report generates at all.** No exception. This is the check that would
   have caught the original bug.
2. **Tool versions resolve.** At least one tool reports a real version rather
   than "-", which is what `tool_env_files` returning nothing looks like from
   the outside -- the failure mode is a report that generates cleanly and says
   nothing useful.
3. **The sections are present.** METHODS, TOOLS & PARAMETERS and REFERENCES all
   appear, and REFERENCES has at least the Snakemake entry `[1]`.

What it cannot check: whether the drafted Methods prose reads well, or whether
a citation is the right paper for the tool. Those are editorial, not mechanical.
"""
import os
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))

import yaml  # noqa: E402

import pipelines  # noqa: E402
import run_report  # noqa: E402
import tool_versions  # noqa: E402

# How many of each pipeline's own tools to switch on. Enough to span several
# categories (so the Methods paragraphs and the category ordering get
# exercised) without making the check slow.
MAX_TOOLS = 12


def build_config(pid: str) -> tuple[str, list]:
    """A minimal config.yaml for `pid`, with some of its real tools active."""
    manifest = pipelines.get_pipeline(pid)
    active = list(manifest.get("tools", {}).keys())[:MAX_TOOLS]
    config = {"active_tools": active, "params": {}, "databases": {}}
    fd, path = tempfile.mkstemp(prefix=f"omniomics_check_{pid}_", suffix=".yaml")
    with os.fdopen(fd, "w") as f:
        yaml.safe_dump(config, f)
    return path, active


def check_pipeline(pid: str) -> int:
    manifest = pipelines.get_pipeline(pid)
    config_path, active = build_config(pid)
    run = {
        "id": "0" * 12,
        "name": f"check-{pid}",
        "started_at": time.time() - 60,
        "finished_at": time.time(),
        "status": "done",
        "exit_code": 0,
        "cores": 4,
        "output_dir": "/tmp/omniomics-check",
    }

    try:
        text = run_report.generate_report(pid, run, config_path)
    except Exception as exc:  # noqa: BLE001 -- reporting it is the whole point
        print(f"  FAIL {pid}: generate_report raised {type(exc).__name__}: {exc}")
        return 1
    finally:
        os.unlink(config_path)

    problems = 0

    # 2. Versions resolved. An empty rule->env map yields a report where every
    #    version is "-", which generates cleanly and tells the reader nothing.
    env_map = tool_versions._rule_env_map(pid)
    if not env_map:
        print(f"  FAIL {pid}: no rule->env mapping found "
              f"(workflow/rules/*.smk not scanned?)")
        problems += 1

    versioned = [t for t in active
                 if tool_versions.primary_version(
                     t, tool_versions.tool_env_files(
                         pid, t, manifest["tools"][t].get("rule_names", [])))]
    if not versioned:
        print(f"  FAIL {pid}: not one of {len(active)} active tools resolved a version")
        problems += 1

    # 3. Sections present.
    for section in ("METHODS", "TOOLS & PARAMETERS", "REFERENCES"):
        if section not in text:
            print(f"  FAIL {pid}: section {section!r} missing from the report")
            problems += 1
    if "[1] " not in text:
        print(f"  FAIL {pid}: REFERENCES has no numbered entries")
        problems += 1

    if not problems:
        print(f"  ok   {pid}: {len(text.splitlines())} lines, "
              f"{len(env_map)} rules mapped, "
              f"{len(versioned)}/{len(active)} tools versioned, "
              f"{text.count(chr(10) + '[')} references")
    return problems


def main() -> int:
    pids = sorted(pipelines.list_pipelines(), key=lambda p: p["id"])
    if not pids:
        print("FAIL: no pipelines found")
        return 1

    print(f"Checking run_report for {len(pids)} pipeline(s):")
    problems = sum(check_pipeline(p["id"]) for p in pids)

    if problems:
        print(f"\nFAIL: {problems} problem(s)")
        return 1
    print("\nOK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
