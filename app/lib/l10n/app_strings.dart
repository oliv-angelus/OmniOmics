/// Locale-aware lookup usable outside build (e.g. in callbacks/snackbars),
/// where `ref.watch` shouldn't be called. `StringsX.t` below is sugar over
/// this for the common in-build case.
String translate(String key, String languageCode) {
  final map = languageCode == 'en' ? _en: _pt;
  return map[key] ?? key;
}

extension StringsX on WidgetRef {
  /// `ref.t('hub_title')` -- rebuilds automatically when localeProvider changes.
  String t(String key) => translate(key, watch(localeProvider).languageCode);
}
